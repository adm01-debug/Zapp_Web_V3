-- 20260915135302 create_prospeccao_schema
-- Schema de prospeccao B2B (empresas-alvo, contatos via Lusha/LeadContact,
-- execucoes de fluxo n8n, config de cookies de sessao). Confirmado via
-- introspecao: RLS DESABILITADO e GRANT a anon nas 4 tabelas — ver CARD 8,
-- tratado como achado de seguranca separado, NAO corrigido nesta migration.
-- --------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS prospeccao;

CREATE TABLE IF NOT EXISTS prospeccao.empresas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome text NOT NULL,
    nome_lusha text,
    setor text,
    cidade text,
    estado character(2),
    prioridade character(1) CHECK (prioridade = ANY (ARRAY['A'::bpchar, 'B'::bpchar, 'C'::bpchar])),
    departamentos text DEFAULT 'COMPRAS,MARKETING,RECURSOS HUMANOS'::text,
    status text NOT NULL DEFAULT 'pendente'::text
        CHECK (status = ANY (ARRAY['pendente'::text, 'em_andamento'::text, 'concluido'::text, 'erro'::text, 'pausado'::text])),
    cod_empresa_bitrix text,
    observacoes text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);
COMMENT ON TABLE prospeccao.empresas IS 'Empresas-alvo para prospecção de brindes corporativos';

CREATE INDEX IF NOT EXISTS idx_empresas_prioridade ON prospeccao.empresas USING btree (prioridade);

CREATE TABLE IF NOT EXISTS prospeccao.contatos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id integer NOT NULL REFERENCES prospeccao.empresas(id) ON DELETE CASCADE,
    nome text,
    cargo text,
    departamento text,
    telefone text,
    linkedin_url text,
    fonte_telefone text CHECK (fonte_telefone = ANY (ARRAY['leadcontact'::text, 'payload_phones'::text, 'manual'::text])),
    status text NOT NULL DEFAULT 'novo'::text
        CHECK (status = ANY (ARRAY['novo'::text, 'contatado'::text, 'aguardando'::text, 'interessado'::text, 'nao_interessado'::text, 'convertido'::text])),
    cod_contato_bitrix text,
    duplicata boolean NOT NULL DEFAULT false,
    notas text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    resumo text,
    localizacao text,
    setor text,
    foto_url text,
    experiencias jsonb DEFAULT '[]'::jsonb,
    competencias text[] DEFAULT '{}'::text[],
    idiomas text[] DEFAULT '{}'::text[],
    interesses text[] DEFAULT '{}'::text[],
    fonte_perfil text,
    telefones_todos jsonb,
    email text[],
    fonte_email text[],
    sobrenome text
);
COMMENT ON TABLE prospeccao.contatos IS 'Contatos encontrados via Lusha/LeadContact para cada empresa';

CREATE INDEX IF NOT EXISTS idx_contatos_email ON prospeccao.contatos USING gin (email);
CREATE INDEX IF NOT EXISTS idx_contatos_empresa ON prospeccao.contatos USING btree (empresa_id);
CREATE INDEX IF NOT EXISTS idx_contatos_linkedin ON prospeccao.contatos USING btree (linkedin_url);
CREATE INDEX IF NOT EXISTS idx_contatos_localizacao ON prospeccao.contatos USING btree (localizacao);

CREATE TABLE IF NOT EXISTS prospeccao.execucoes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id integer NOT NULL REFERENCES prospeccao.empresas(id) ON DELETE CASCADE,
    departamento text,
    total_encontrados integer DEFAULT 0,
    total_inseridos integer DEFAULT 0,
    total_duplicatas integer DEFAULT 0,
    status text NOT NULL DEFAULT 'iniciado'::text
        CHECK (status = ANY (ARRAY['iniciado'::text, 'concluido'::text, 'erro'::text, 'sem_resultado'::text])),
    erro_msg text,
    executado_por text,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);
COMMENT ON TABLE prospeccao.execucoes IS 'Histórico de cada execução do fluxo n8n por empresa/departamento';

CREATE INDEX IF NOT EXISTS idx_execucoes_empresa ON prospeccao.execucoes USING btree (empresa_id);

