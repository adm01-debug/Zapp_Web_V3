CREATE OR REPLACE FUNCTION prospeccao.set_updated_at() RETURNS trigger
    LANGUAGE plpgsql
    AS $function$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS trg_contatos_updated_at ON prospeccao.contatos;
CREATE TRIGGER trg_contatos_updated_at BEFORE UPDATE ON prospeccao.contatos
  FOR EACH ROW EXECUTE FUNCTION prospeccao.set_updated_at();

DROP TRIGGER IF EXISTS trg_empresas_updated_at ON prospeccao.empresas;
CREATE TRIGGER trg_empresas_updated_at BEFORE UPDATE ON prospeccao.empresas
  FOR EACH ROW EXECUTE FUNCTION prospeccao.set_updated_at();

